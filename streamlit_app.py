"""
Warehouse Management AI Chatbot (Streamlit)
Retrieval-Augmented Generation over warehouse documents and scored orders, answered by Claude.
"""
import os

import streamlit as st

st.set_page_config(page_title="Warehouse Management AI Chatbot", page_icon="📦", layout="wide")


@st.cache_resource(show_spinner="Building the knowledge index...")
def load_rag():
    import rag
    return rag


rag = load_rag()


def secret(name, default=None):
    try:
        return st.secrets.get(name, os.environ.get(name, default))
    except Exception:
        return os.environ.get(name, default)


API_KEY = secret("ANTHROPIC_API_KEY")
MODEL = secret("CLAUDE_MODEL", "claude-sonnet-5-5")


@st.cache_resource
def get_client(key):
    import anthropic
    return anthropic.Anthropic(api_key=key)


client = get_client(API_KEY) if API_KEY else None

EXAMPLES = [
    "Which orders are at the highest risk right now?",
    "Why is SO-92802 likely to ship late and what should I do?",
    "What should a supervisor do when items are only in reserve locations?",
    "Which picking zone has the highest late rate?",
    "How accurate is the delay prediction model?",
    "Why are Monday orders more likely to be late?",
]

st.title("📦 Warehouse Management AI Chatbot")
st.caption("Ask about at-risk orders, delay drivers, and what to do. Answers are generated by Claude from retrieved "
           "warehouse documents and scored orders (RAG). Scored orders cover April to June 2026. All data is synthetic.")

chat_tab, dash_tab, about_tab = st.tabs(["Chat", "Risk dashboard", "About"])

# ------------------------------------------------------------------ chat
with chat_tab:
    if "messages" not in st.session_state:
        st.session_state.messages = []
    if client is None:
        st.warning("The language model is not configured. Add ANTHROPIC_API_KEY in the app's Secrets settings.")

    st.markdown("**Try a question:**")
    cols = st.columns(3)
    clicked = None
    for i, q in enumerate(EXAMPLES):
        if cols[i % 3].button(q, key=f"ex{i}", width="stretch"):
            clicked = q
    if st.session_state.messages and st.button("Clear chat"):
        st.session_state.messages = []
        st.rerun()

    for m in st.session_state.messages:
        with st.chat_message(m["role"]):
            st.markdown(m["content"])
            if m.get("sources"):
                with st.expander("Sources"):
                    st.markdown(m["sources"])

    prompt = st.chat_input("Ask about orders, zones, carriers, or actions") or clicked
    if prompt:
        with st.chat_message("user"):
            st.markdown(prompt)
        context, sources = rag.retrieve(prompt)
        numbered = "\n\n".join(f"[{i+1}] (source: {s})\n{c}" for i, (c, s) in enumerate(zip(context, sources)))
        source_md = "\n".join(f"{i+1}. {s}" for i, s in enumerate(sources)) or "No matching passages"

        with st.chat_message("assistant"):
            if client is None:
                answer = "The language model is not configured yet. Here is what the retriever found:\n\n" + numbered[:3000]
                st.markdown(answer)
            else:
                history = [{"role": m["role"], "content": m["content"]} for m in st.session_state.messages[-6:]]
                history.append({"role": "user", "content": f"Context passages:\n\n{numbered}\n\nQuestion: {prompt}"})

                def stream():
                    with client.messages.stream(model=MODEL, max_tokens=900, system=rag.SYSTEM,
                                                messages=history) as s:
                        yield from s.text_stream
                try:
                    answer = st.write_stream(stream())
                except Exception as e:
                    answer = f"Sorry, the language model call failed: {e}"
                    st.error(answer)
            with st.expander("Sources"):
                st.markdown(source_md)
        st.session_state.messages.append({"role": "user", "content": prompt})
        st.session_state.messages.append({"role": "assistant", "content": answer, "sources": source_md})

# ------------------------------------------------------------------ dashboard
with dash_tab:
    st.markdown("High-risk orders (delay probability at or above the alert threshold), ranked by probability.")
    orders = rag.orders
    c1, c2 = st.columns(2)
    zone = c1.selectbox("Zone", ["All", "A", "B", "C", "D"])
    days = ["All"] + sorted(orders.release_ts.str[:10].unique(), reverse=True)
    day = c2.selectbox("Release date", days)
    d = orders[orders.risk_level == "High"]
    if zone != "All":
        d = d[d.dominant_zone == zone]
    if day != "All":
        d = d[d.release_ts.str.startswith(day)]
    k1, k2, k3 = st.columns(3)
    k1.metric("High-risk orders", f"{len(d):,}")
    k2.metric("Average delay probability", f"{d.delay_probability.mean():.0%}" if len(d) else "n/a")
    k3.metric("Actually shipped late", f"{d.is_late.mean():.0%}" if len(d) else "n/a")
    cols = ["order_id", "release_ts", "required_ship_by_ts", "dominant_zone", "lines_count", "pickers_on_shift",
            "hours_to_cutoff", "delay_probability", "risk_drivers", "suggested_action"]
    st.dataframe(d.sort_values("delay_probability", ascending=False)[cols], hide_index=True,
                 width="stretch",
                 column_config={"delay_probability": st.column_config.ProgressColumn(
                     "delay_probability", format="%.2f", min_value=0.0, max_value=1.0)})

# ------------------------------------------------------------------ about
with about_tab:
    st.markdown(open(os.path.join(os.path.dirname(__file__), "knowledge/solution_overview.md")).read())
